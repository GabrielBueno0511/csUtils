-- Run against a NEW Supabase project. Existing SQLite data is left untouched.
create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name varchar(80) not null check (char_length(btrim(name)) between 2 and 80)
);

create function app_private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, name) values (new.id,
    case when char_length(btrim(coalesce(new.raw_user_meta_data ->> 'name', ''))) >= 2
      then left(btrim(new.raw_user_meta_data ->> 'name'), 80) else 'Jogador' end);
  return new;
end;
$$;
revoke all on function app_private.handle_new_user() from public, anon, authenticated;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function app_private.handle_new_user();

create table public.utilities (
  id integer generated by default as identity primary key,
  author_id uuid constraint utilities_author_id_fkey references public.profiles(id) on delete set null,
  spot_id varchar(50) not null check (char_length(btrim(spot_id)) between 1 and 50),
  spot_name varchar(100) not null check (char_length(btrim(spot_name)) between 1 and 100),
  map_name varchar(50) not null check (map_name in ('dust2','mirage','inferno','nuke','ancient','anubis','cache')),
  throw_type varchar(50) not null check (throw_type in ('normal','jump-throw','run-throw','crouch-throw','walk-throw')),
  -- Storage object paths, NEVER base64 or user-provided external URLs.
  player_position_image text not null check (char_length(player_position_image) between 1 and 500),
  aim_position_image text not null check (char_length(aim_position_image) between 1 and 500),
  legacy_id integer unique,
  legacy_author_name varchar(80),
  created_at timestamptz not null default now()
);
create index utilities_map_id_idx on public.utilities(map_name, id desc);
create index utilities_author_idx on public.utilities(author_id);

create table public.utility_favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  utility_id integer not null references public.utilities(id) on delete cascade,
  primary key(user_id, utility_id)
);
create index utility_favorites_utility_idx on public.utility_favorites(utility_id);

alter table public.profiles enable row level security;
alter table public.utilities enable row level security;
alter table public.utility_favorites enable row level security;
revoke all on public.profiles, public.utilities, public.utility_favorites from anon, authenticated;
grant select on public.profiles, public.utilities to anon, authenticated;
grant delete on public.utilities to authenticated;
grant insert (author_id, spot_id, spot_name, map_name, throw_type, player_position_image, aim_position_image)
  on public.utilities to authenticated;
grant usage on sequence public.utilities_id_seq to authenticated;
grant select, insert, delete on public.utility_favorites to authenticated;
-- Explicit grants also support projects with automatic table exposure disabled.
grant all on public.profiles, public.utilities, public.utility_favorites to service_role;
grant usage, select on sequence public.utilities_id_seq to service_role;

create policy profiles_public_read on public.profiles for select to anon, authenticated using (true);
create policy utilities_public_read on public.utilities for select to anon, authenticated using (true);
create policy utilities_owner_insert on public.utilities for insert to authenticated
  with check (
    author_id = (select auth.uid())
    and (storage.foldername(player_position_image))[1] = (select auth.uid())::text
    and (storage.foldername(aim_position_image))[1] = (select auth.uid())::text
    and exists (select 1 from storage.objects o where o.bucket_id = 'utility-images' and o.name = player_position_image)
    and exists (select 1 from storage.objects o where o.bucket_id = 'utility-images' and o.name = aim_position_image)
  );
create policy utilities_owner_delete on public.utilities for delete to authenticated
  using (author_id = (select auth.uid()));
create policy favorites_owner_read on public.utility_favorites for select to authenticated
  using (user_id = (select auth.uid()));
create policy favorites_owner_insert on public.utility_favorites for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy favorites_owner_delete on public.utility_favorites for delete to authenticated
  using (user_id = (select auth.uid()));

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('utility-images', 'utility-images', true, 5242880, array['image/png','image/jpeg','image/webp']);

-- Public bucket serves screenshots; listing and deletion remain scoped to the owner.
create policy utility_images_owner_read on storage.objects for select to authenticated
  using (bucket_id = 'utility-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy utility_images_owner_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'utility-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy utility_images_owner_delete on storage.objects for delete to authenticated
  using (
    bucket_id = 'utility-images' and (storage.foldername(name))[1] = (select auth.uid())::text
    and not exists (select 1 from public.utilities u
      where u.player_position_image = name or u.aim_position_image = name)
  );
